export function getTitle(id: string): Title | undefined {
  return titles.find((t) => t.id === id)
}

export function recommendations(forId: string, limit = 6): Title[] {
  const base = getTitle(forId)
  if (!base) return titles.slice(0, limit)
  return titles
    .filter((t) => t.id !== forId)
    .map((t) => ({
      t,
      score: t.genres.filter((g) => base.genres.includes(g)).length + (t.kind === base.kind ? 1 : 0),
    }))
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((x) => x.t)
}
